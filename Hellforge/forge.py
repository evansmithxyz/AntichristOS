def cmd_boot(a):
    out = a.out or os.path.join(OUT, a.prefix + ".ISO.C")
    if not a.no_build:
        mkiso.make_iso(a.src, out, log=log, **iso_kwargs(a))
    shots = [float(s) for s in a.shots.split(",") if s]
    r = qemu.run(out, timeout=a.seconds, shots=shots, shot_every=a.every,
                 shot_prefix=a.prefix, serial=os.path.join(OUT, a.prefix + ".serial.txt"),
                 keys=qemu.parse_keys(a.keys), accel=a.accel, mem=a.mem, smp=a.smp,
                 log=log, name=a.prefix)
    log(f"boot: accel={r['accel']} ran {r['elapsed']:.1f}s rc={r['rc']} shots={len(r['shots'])}")
    for s in r["shots"]:
        print(s)
    return 0


# ---------------------------------------------------------------- serial
_DD_TEXT = re.compile(r'^(?:LK|TX|BT|MA|MU|CB|LS|DA|HC)[^,]*,"((?:[^"\\]|\\.)*)"')


def dd_plain(s):
    """Render DolDoc markup ($LK..$, $FG..$, $$) as plain text for the console.
    The raw serial file keeps the original bytes."""
    out, i = [], 0
    while i < len(s):
        j = s.find("$", i)
        if j < 0:
            out.append(s[i:])
            break
        out.append(s[i:j])
        if s[j + 1:j + 2] == "$":
            out.append("$")
            i = j + 2
            continue
        k = s.find("$", j + 1)
        if k < 0:
            out.append(s[j:])
            break
        m = _DD_TEXT.match(s[j + 1:k])
        if m:
            out.append(m.group(1))
        i = k + 1
    return "".join(out)


def safe_rel(name):
    """Dump name from the guest -> safe relative host path (keeps subdirs)."""
    parts = [re.sub(r"[^A-Za-z0-9._-]+", "_", p)
             for p in name.replace("\\", "/").split("/")]
    parts = [p for p in parts if p not in ("", ".", "..")]
    return os.path.join(*parts) if parts else "dump"


class SerialParser:
    """Parses the Hellforge COM1 protocol (see guest/Serial.HC).

    echo: True (print every line), False, or a predicate(line)->bool.
    feed() returns the screenshot names the guest asked for (HfShot)."""
    EVENTS = ("HELLFORGE_STARTOS_END", "HELLFORGE_READY", "HELLFORGE_EXIT",
              "HELLFORGE_EXCEPT")

    def __init__(self, echo=True, dump_dir=None):
        self.buf = b""
        self.echo = echo
        self.dump_dir = dump_dir or os.path.join(OUT, "dumps")
        self.dump = None
        self.dumps = []
        self.events = {}
        self.lines = []
        self.doc = None
        self._in_doc = False
        self._doc_lines = []
        self._shots = []
        self.t0 = time.monotonic()

    def feed(self, chunk):
        self.buf += chunk
        while b"\n" in self.buf:
            line, self.buf = self.buf.split(b"\n", 1)
            self.line(line.rstrip(b"\r").decode("latin-1"))
        shots, self._shots = self._shots, []
        return shots

    def line(self, s):
        now = time.monotonic() - self.t0
        if s.startswith("HFD ") and self.dump is not None:
            try:
                self.dump["data"] += bytes.fromhex(s[4:].strip())
            except ValueError:
                self.dump["bad_lines"] += 1
            return
        if self._in_doc:
            if s.startswith("HELLFORGE_DOC_END"):
                self._in_doc = False
                self.doc = "\n".join(self._doc_lines)
            else:
                self._doc_lines.append(s)
                if self.echo is True:
                    print(dd_plain(s), flush=True)
                return
        elif s.startswith("HELLFORGE_DOC_BEGIN"):
            self._in_doc = True
            self._doc_lines = []
        m = re.match(r"HFDUMP BEGIN (\S+) (\d+)", s)
        if m:
            self.dump = dict(name=m.group(1), size=int(m.group(2)), data=b"",
                             bad_lines=0)
        m2 = re.match(r"HFDUMP END ([0-9A-Fa-f]+)", s)
        if m2 and self.dump is not None:
            d = self.dump
            ok = (zlib.crc32(d["data"]) == int(m2.group(1), 16)
                  and len(d["data"]) == d["size"] and not d["bad_lines"])
            path = os.path.join(self.dump_dir, safe_rel(d["name"]))
            os.makedirs(os.path.dirname(path), exist_ok=True)
            with open(path, "wb") as f:
                f.write(d["data"])
            d.update(ok=ok, path=path, crc=int(m2.group(1), 16))
            self.dumps.append(d)
            self.dump = None
            s += f"   [host: {len(d['data'])} bytes -> {path} crc {'OK' if ok else 'MISMATCH'}]"
        m3 = re.match(r"HELLFORGE_SHOT ([A-Za-z0-9_-]+)", s)
        if m3:
            self._shots.append(m3.group(1))
        for key in self.EVENTS:
            if s.startswith(key) and key not in self.events:
                self.events[key] = (now, s)
        self.lines.append(s)
        if self.echo is True or (callable(self.echo) and self.echo(s)):
            print(dd_plain(s), flush=True)

    def dump_named(self, name):
        """Last dump called name, or None."""
        for d in reversed(self.dumps):
            if d["name"] == name:
                return d
        return None


# ---------------------------------------------------------------- run
def anchor_spec(a):
    """qemu.run(anchor=...) for --anchor-ready (0 is a valid time: every
    scripted time then counts from HELLFORGE_READY)."""
    t = getattr(a, "anchor_ready", None)
    return None if t is None else (b"HELLFORGE_READY", t)


def run_guest(a, test, name, extra_add=(), src=None, echo=True):
    """Build an ISO from src (default a.src) whose autorun executes `test`
    (a host path, or bytes), boot it and parse COM1.

    Everything goes to out/run/<name>/: Test.ISO.C, serial.txt, dumps/,
    <name>_*.png screenshots, <name>.qemu-stderr.txt.
    Returns dict(code, why, r, sp, workdir, serial, iso, shots)."""
    wd = os.path.join(OUT, "run", name)
    os.makedirs(wd, exist_ok=True)
    wrapper = os.path.join(wd, "AutoRun.HC")
    with open(wrapper, "w", newline="\n") as f:
        f.write(WRAPPER.replace("%(settle_ms)d", str(int(a.settle * 1000)))
                .replace("%(dump_doc)d", "0" if a.no_doc else "1")
                .replace("%(fail_shot)d", "0" if a.no_fail_shot else "1"))
    if isinstance(test, (bytes, bytearray)):
        test_path = os.path.join(wd, "Test.HC")
        with open(test_path, "wb") as f:
            f.write(test)
    else:
        test_path = test
    iso = getattr(a, "iso_out", None) or os.path.join(wd, "Test.ISO.C")
    kw = iso_kwargs(a)
    kw["add"] = kw["add"] + [(SERIAL_HC, "Hellforge/Serial.HC"),
                             (test_path, "Hellforge/Test.HC")] + list(extra_add)
    t_build = time.monotonic()
    mkiso.make_iso(src or a.src, iso, inject_autorun=wrapper, log=log, **kw)
    log(f"built {iso} in {time.monotonic()-t_build:.2f}s")

    sp = SerialParser(echo=echo, dump_dir=os.path.join(wd, "dumps"))
    serial = os.path.join(wd, "serial.txt")
    bt = a.boot_timeout
    if bt is None:
        bt = 120   # boot takes ~10 s, patched or not (since the bootstrapped .MAPs)
    expect = []
    if bt and bt < a.timeout:
        expect.append((bt, b"HELLFORGE_STARTOS_END",
                       f"StartOS did not finish within {bt:g}s"))
    shots = [float(s) for s in a.shots.split(",") if s]
    r = qemu.run(iso, timeout=a.timeout, shots=shots, shot_every=a.every,
                 shot_prefix=name, shot_dir=wd, serial=serial,
                 keys=qemu.parse_keys(a.keys), accel=a.accel, mem=a.mem, smp=a.smp,
                 log=log, name=name, stream=sp.feed, expect=expect,
                 anchor=anchor_spec(a))
    sp.feed(b"\n")
    ev = sp.events
    if "HELLFORGE_STARTOS_END" in ev:
        log(f"StartOS end at {ev['HELLFORGE_STARTOS_END'][0]:.1f}s host "
            f"({ev['HELLFORGE_STARTOS_END'][1].split()[1]} ms guest tS)")
    if "HELLFORGE_READY" in ev:
        log(f"autorun ready at {ev['HELLFORGE_READY'][0]:.1f}s host "
            f"({ev['HELLFORGE_READY'][1].split()[1]} ms guest tS)")
    log(f"qemu accel={r['accel']} elapsed={r['elapsed']:.1f}s rc={r['rc']} "
        f"guest_code={r['guest_code']} timed_out={r['timed_out']}")
    if r.get("stalled"):
        code, why = 124, r["stalled"]
    elif r["timed_out"]:
        code, why = 124, f"timeout after {a.timeout:g}s"
    elif r["guest_code"] is None:
        code, why = 125, f"QEMU exited without isa-debug-exit (rc={r['rc']}; " \
                         f"triple fault/reset with -no-reboot?)"
    else:
        code = r["guest_code"]
        why = EXIT_MEANING.get(code, "guest exit code")
    if code in (124, 125):
        if "HELLFORGE_STARTOS_END" not in ev:
            log("the guest never reached the autorun: StartOS.HC (Adam, MakeHome, "
                "~/Home*.HC) failed to compile/run or hung -- see the screenshot")
        elif "HELLFORGE_READY" not in ev:
            log("StartOS finished but Adam never entered server mode")
        else:
            log("the test itself hung or crashed the machine")
        err = (r.get("stderr") or "").strip()
        if err:
            log("qemu stderr: " + err[-500:])
    log(f"result: {code} ({why})")
    log(f"serial log: {serial}")
    for p in r["shots"]:
        log(f"screenshot: {p}")
    return dict(code=code, why=why, r=r, sp=sp, workdir=wd, serial=serial, iso=iso,
                shots=r["shots"])


def cmd_run(a):
    if a.eval is not None:
        if a.file:
            log("give either FILE or --eval, not both")
            return 125
        test = a.eval.encode("latin-1") + b"\n"
        stem = "eval"
    elif a.file == "-":
        test = sys.stdin.buffer.read()
        stem = "stdin"
    elif a.file:
        if not os.path.isfile(a.file):
            log(f"no such file: {a.file}")
            return 125
        test = os.path.abspath(a.file)
        stem = os.path.basename(a.file).split(".")[0]
    else:
        log("nothing to run: give FILE.HC, '-' (stdin) or --eval CODE")
        return 125
    name = a.name or re.sub(r"[^A-Za-z0-9_-]+", "_", stem) or "run"
    res = run_guest(a, test, name, echo=not a.quiet)
    if a.quiet and res["code"] != 0 and res["sp"].doc:
        print(dd_plain(res["sp"].doc))
    return res["code"]


