def hc_str(s):
    """Python str -> HolyC string literal (DolDoc source: '$' is '$$')."""
    out = []
    for ch in s:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\t":
            out.append("\\t")
        elif ch == "$":
            out.append("$$")
        elif 32 <= ord(ch) < 127:
            out.append(ch)
        else:
            raise ValueError(f"unsupported character {ch!r} in {s!r}")
    return '"' + "".join(out) + '"'


def cdate_decode(ct):
    """64-bit CDate -> 'YYYY-MM-DD HH:MM:SS' (inverse of mkiso.cdate)."""
    date = (ct >> 32) & 0xFFFFFFFF
    if date & 0x80000000:
        date -= 1 << 32
    tm = ct & 0xFFFFFFFF
    year = max(1, date * 400 // 146097)
    while mkiso._year_start_date(year) > date:
        year -= 1
    while mkiso._year_start_date(year + 1) <= date:
        year += 1
    i1 = mkiso._year_start_date(year)
    i2 = mkiso._year_start_date(year + 1)
    mon = mkiso._MON1 if i2 - i1 == 365 else mkiso._MON2
    doy = date - i1
    m = max(k for k in range(12) if mon[k] <= doy)
    day = doy - mon[m] + 1
    total = tm * (15 * 15 * 3 * 625) >> 21          # 1/10000 s since midnight
    secs = total // 10000
    return (f"{year:04d}-{m + 1:02d}-{day:02d} "
            f"{secs // 3600:02d}:{secs // 60 % 60:02d}:{secs % 60:02d}")


def cfg_unescape(s):
    """--cfg as typed on a shell: backslash escapes (\\n, \\t, \\\\, \\xHH)
    become the characters KCfg should get.  Real newlines pass through."""
    try:
        return s.encode("latin-1", "backslashreplace").decode("unicode_escape")
    except UnicodeDecodeError as e:
        raise ValueError(f"bad escape in --cfg {s!r}: {e}")


def bs_trees(a):
    """Kernel and Compiler, plus any --tree dirs (additive, no duplicates)."""
    trees = list(BS_TREES)
    for t in (x.replace("\\", "/").strip("/") for x in a.tree):
        if t and t not in trees:
            trees.append(t)
    return trees


def bs_prelude(a):
    trees = bs_trees(a)
    drv = a.drv.upper()
    if not ("A" <= drv <= "Z" and len(drv) == 1):
        raise ValueError(f"bad --drv {a.drv!r}")
    lines = ["//Generated by forge.py bootstrap (ISO-only, not in repo)",
             f"U8 hf_bs_drv='{drv}';",
             f"U8 *hf_bs_cfg={hc_str(cfg_unescape(a.cfg))};",
             f"U8 *hf_bs_trees[{len(trees) + 1}]={{"
             + ",".join(hc_str(t) for t in trees) + ",NULL};",
             f"Bool hf_bs_bootdvdins={'TRUE' if a.bootdvdins else 'FALSE'};", ""]
    return "\n".join(lines).encode("latin-1")


def _bs_echo(s):
    return s.startswith(("HFBS", "HELLFORGE_", "HFDUMP", "HFVF"))


def bootstrap_once(a, name, src=None, overlay_dir=None):
    """One in-guest rebuild.  overlay_dir: host dir with BS_FILES to put into
    the image first (stage 2+: boot the binaries built by the previous stage)."""
    extra = []
    if overlay_dir:
        for rel in BS_FILES:
            extra.append((os.path.join(overlay_dir, *rel.split("/")), rel))
    with open(os.path.join(GUEST, "Bootstrap.HC"), "rb") as f:
        test = bs_prelude(a) + f.read()
    t0 = time.monotonic()
    res = run_guest(a, test, name, extra_add=extra, src=src,
                    echo=True if a.verbose else _bs_echo)
    sp = res["sp"]
    problems = []
    if res["code"] != 0:
        problems.append(f"guest exit {res['code']}: "
                        f"{BS_EXIT.get(res['code'], res['why'])}")
    files = {}
    for rel in BS_FILES:
        d = sp.dump_named(rel)
        if d is None:
            problems.append(f"{rel}: not received")
        elif not d["ok"]:
            problems.append(f"{rel}: CRC/size mismatch on serial")
        else:
            files[rel] = d["data"]
    for rel in BS_BINS:
        if rel in files and files[rel][4:8] != b"TOSB":
            problems.append(f"{rel}: no TOSB signature")
    ct = None
    if KERNEL_BIN in files:
        ct = struct.unpack_from("<Q", files[KERNEL_BIN], KERNEL_CT_OFF)[0]
    hfbs = [s for s in sp.lines if s.startswith("HFBS")]
    timing = {}
    for s in hfbs:
        m = re.match(r"HFBS CMP_(BEGIN|END) (\w+).* (\d+)$", s)
        if m:
            timing.setdefault(m.group(2), {})[m.group(1)] = int(m.group(3))
    cmp_ms = {k: v["END"] - v["BEGIN"] for k, v in timing.items()
              if "BEGIN" in v and "END" in v}
    if problems and sp.doc and not a.verbose:
        print("---- guest terminal (bootstrap task) ----")
        print(dd_plain(sp.doc))
        print("---- end guest terminal ----")
    return dict(ok=not problems, problems=problems, files=files, code=res["code"],
                res=res, compile_time=ct, hfbs=hfbs, cmp_ms=cmp_ms,
                elapsed=time.monotonic() - t0)


def write_outputs(out_dir, b, src):
    os.makedirs(out_dir, exist_ok=True)
    man = dict(src=os.path.abspath(src), accel=b["res"]["r"]["accel"],
               host_seconds=round(b["elapsed"], 1), compile_ms=b["cmp_ms"],
               serial=b["res"]["serial"], files={}, hfbs=b["hfbs"])
    if b["compile_time"] is not None:
        man["kernel_compile_time"] = "0x%016X" % b["compile_time"]
        man["kernel_compile_time_decoded"] = cdate_decode(b["compile_time"])
    for rel, data in b["files"].items():
        p = os.path.join(out_dir, *rel.split("/"))
        os.makedirs(os.path.dirname(p), exist_ok=True)
        with open(p, "wb") as f:
            f.write(data)
        man["files"][rel] = dict(size=len(data), crc32="%08X" % zlib.crc32(data),
                                 sha1=hashlib.sha1(data).hexdigest())
    with open(os.path.join(out_dir, "bootstrap.json"), "w", newline="\n") as f:
        json.dump(man, f, indent=1)
    return man


def _runs(new, old):
    n = min(len(new), len(old))
    runs, i = [], 0
    while i < n:
        if new[i] != old[i]:
            j = i + 1
            while j < n and new[j] != old[j]:
                j += 1
            runs.append((i, j))
            i = j
        else:
            i += 1
    return runs


def diff_summary(rel, new, old):
    """Human-readable byte diff of one bootstrapped file against a reference."""
    lines = []
    if old is None:
        return [f"{rel}: no reference file"]
    if new == old:
        return [f"{rel}: identical ({len(new)} bytes)"]
    runs = _runs(new, old)
    nbytes = sum(e - s for s, e in runs) + abs(len(new) - len(old))
    lines.append(f"{rel}: new {len(new)} bytes, ref {len(old)} bytes "
                 f"({len(new) - len(old):+d}); {nbytes} positional bytes differ "
                 f"in {len(runs)} runs")
    if rel in BS_BINS:
        ct, pad, other = [], [], []
        for s, e in runs:
            if rel == KERNEL_BIN and KERNEL_CT_OFF <= s and e <= KERNEL_CT_OFF + 8:
                ct.append((s, e))
                continue
            blk_end = (e + 15) & ~15
            if (s >> 4) == ((e - 1) >> 4) and new[blk_end:blk_end + 1] == b"\x55" \
                    and old[blk_end:blk_end + 1] == b"\x55":
                pad.append((s, e))   # tail of a 16-byte block before PUSH RBP
            else:
                other.append((s, e))
        if ct:
            lines.append(f"  compile_time @0x{KERNEL_CT_OFF:X}: new "
                         f"{cdate_decode(struct.unpack_from('<Q', new, KERNEL_CT_OFF)[0])}"
                         f", ref {cdate_decode(struct.unpack_from('<Q', old, KERNEL_CT_OFF)[0])}")
        lines.append(f"  {len(pad)} runs / {sum(e - s for s, e in pad)} bytes are "
                     f"ALIGN padding before a function prologue (PUSH RBP)")
        lines.append(f"  {len(other)} runs / {sum(e - s for s, e in other)} bytes "
                     f"elsewhere (padding inside data tables or real changes):")
        for s, e in other[:12]:
            lines.append(f"    0x{s:05X}-0x{e:05X} new {new[s:e].hex()} ref {old[s:e].hex()}")
        if len(other) > 12:
            lines.append(f"    ... {len(other) - 12} more")
    else:
        tn, to = new.split(b"\0", 1)[0], old.split(b"\0", 1)[0]
        lines.append(f"  DolDoc text part: {'identical' if tn == to else 'differs'} "
                     f"({len(tn)} vs {len(to)} bytes); bin tail {len(new) - len(tn)} vs "
                     f"{len(old) - len(to)} bytes")
        n5 = new.count(5)
        if n5 and not old.count(5):
            stripped = new.replace(b"\x05", b"")
            same = sum(1 for x, y in zip(stripped, old) if x != y)
            lines.append(f"  new has {n5} 0x05 bytes, ref has none (the repo's "
                         f"stripped-0x05 damage); new minus 0x05 vs ref: "
                         f"{'identical' if stripped == old else f'{same} bytes differ'}")
    return lines


def report_diffs(files, ref_root, title):
    print(f"==== byte diff: {title} ====")
    for rel in BS_FILES:
        if rel not in files:
            continue
        rp = os.path.join(ref_root, *rel.split("/"))
        old = open(rp, "rb").read() if os.path.isfile(rp) else None
        for ln in diff_summary(rel, files[rel], old):
            print(ln)


def install_files(files, root):
    for rel, data in files.items():
        p = os.path.join(root, *rel.split("/"))
        os.makedirs(os.path.dirname(p), exist_ok=True)
        with open(p, "wb") as f:
            f.write(data)
        log(f"installed {rel} ({len(data)} bytes) -> {p}")


def _bs_fail(b):
    for p in b["problems"]:
        log("bootstrap FAILED: " + p)
    if b["code"] in (124, 125, 126):
        return b["code"]
    return 1


def cmd_bootstrap(a):
    out_dir = os.path.abspath(a.out_dir or os.path.join(OUT, "bootstrap"))
    prev, b = None, None
    for st in range(1, a.stages + 1):
        name = "bootstrap" if a.stages == 1 else f"bootstrap{st}"
        log(f"stage {st}/{a.stages}: rebuilding in the guest"
            + (f" (booting stage {st - 1} binaries)" if prev else ""))
        b = bootstrap_once(a, name, overlay_dir=prev)
        if not b["ok"]:
            return _bs_fail(b)
        sdir = out_dir if st == a.stages else os.path.join(out_dir, f"stage{st}")
        man = write_outputs(sdir, b, a.src)
        log(f"stage {st}: compile ms {b['cmp_ms']}, total {b['elapsed']:.1f}s, kernel "
            f"compile_time {man.get('kernel_compile_time_decoded')} -> {sdir}")
        if prev:
            report_diffs(b["files"], prev, f"stage {st} vs stage {st - 1}")
        prev = sdir
    report_diffs(b["files"], a.src, f"bootstrap output vs {a.src}")
    for rel in BS_FILES:
        print(f"OUTPUT {os.path.join(out_dir, *rel.split('/'))}")
    if a.install:
        install_files(b["files"], os.path.abspath(a.install_root or a.src))
    return 0


# ---------------------------------------------------------------- selftest
def _sha1(p):
    with open(p, "rb") as f:
        return hashlib.sha1(f.read()).hexdigest()


def cmd_selftest(a):
    """bootstrap -> diff -> install into a scratch copy of the tree -> boot
    it and check sys_compile_time/file CRCs + desktop screenshot -> stage-2
    rebuild on the new binaries and compare (fixpoint)."""
    t_all = time.monotonic()
    root = os.path.join(OUT, "selftest")
    os.makedirs(root, exist_ok=True)
    src = os.path.abspath(a.src)
    guard = {rel: _sha1(os.path.join(src, *rel.split("/"))) for rel in BS_FILES}
    results = []

    def step(nm, ok, info=""):
        results.append((nm, ok, info))
        log(f"selftest: {nm}: {'PASS' if ok else 'FAIL'} {info}")

    # 1. bootstrap from the unmodified sources
    b1 = bootstrap_once(a, "selftest-bootstrap")
    if not b1["ok"]:
        step("bootstrap", False, "; ".join(b1["problems"]))
        return _bs_fail(b1)
    man1 = write_outputs(os.path.join(root, "bootstrap"), b1, src)
    step("bootstrap", True, f"{b1['elapsed']:.1f}s, compile ms {b1['cmp_ms']}, "
         f"kernel compile_time {man1.get('kernel_compile_time_decoded')}")
    # 2. diff against the repo's binaries
    report_diffs(b1["files"], src, "bootstrap vs repo")
    sizes_ok = all(len(b1["files"][rel]) > 0 for rel in BS_FILES)
    step("diff", sizes_ok, "see byte diff above")
    # 3. scratch copy of the tree with the new binaries installed
    scratch = os.path.join(root, "scratch")
    if os.path.isdir(scratch):
        shutil.rmtree(scratch)
    t = time.monotonic()
    shutil.copytree(src, scratch, ignore=shutil.ignore_patterns(
        ".git", "Hellforge", ".claude", "__pycache__"))
    install_files(b1["files"], scratch)
    step("scratch-install", True, f"{scratch} ({time.monotonic() - t:.1f}s)")
    # 4. boot the scratch tree, verify the new kernel/compiler are in use
    kern, comp = b1["files"][KERNEL_BIN], b1["files"]["Compiler/Compiler.BIN"]
    pre = "\n".join([
        "//Generated by forge.py selftest (ISO-only)",
        f"I64 hf_vf_compile_time=0x{b1['compile_time']:X};",
        f"I64 hf_vf_kernel_size={len(kern)},hf_vf_kernel_crc=0x{zlib.crc32(kern):08X};",
        f"I64 hf_vf_compiler_size={len(comp)},hf_vf_compiler_crc=0x{zlib.crc32(comp):08X};",
        ""]).encode("latin-1")
    with open(os.path.join(GUEST, "VerifyBoot.HC"), "rb") as f:
        test = pre + f.read()
    v = run_guest(a, test, "selftest-verify", src=scratch,
                  echo=True if a.verbose else _bs_echo)
    desk = [p for p in v["shots"] if p.endswith("_desktop.png")]
    hfvf = [s for s in v["sp"].lines if s.startswith("HFVF")]
    step("boot-new-binaries", v["code"] == 0 and bool(desk),
         f"code {v['code']} ({v['why']}); {' | '.join(hfvf)}; screenshot "
         f"{desk[0] if desk else 'MISSING'}")
    # 5. stage 2: the new compiler rebuilds everything from the scratch tree
    if not a.no_stage2:
        b2 = bootstrap_once(a, "selftest-stage2", src=scratch)
        if b2["ok"]:
            write_outputs(os.path.join(root, "stage2"), b2, scratch)
            report_diffs(b2["files"], os.path.join(root, "bootstrap"),
                         "stage 2 (built by the new binaries) vs stage 1")
            same_size = all(len(b2["files"][r]) == len(b1["files"][r]) for r in BS_FILES)
            step("stage2", same_size, f"{b2['elapsed']:.1f}s, sizes "
                 f"{'match' if same_size else 'DIFFER'} stage 1")
        else:
            step("stage2", False, "; ".join(b2["problems"]))
    # 6. the repo's own binaries must be untouched
    after = {rel: _sha1(os.path.join(src, *rel.split("/"))) for rel in BS_FILES}
    step("repo-untouched", after == guard)
    ok = all(r[1] for r in results)
    print("==== selftest summary ====")
    for nm, good, info in results:
        print(f"{'PASS' if good else 'FAIL'}  {nm}  {info}")
    print(f"selftest {'PASSED' if ok else 'FAILED'} in {time.monotonic() - t_all:.1f}s")
    return 0 if ok else 1


